const EN_LABELS: PdfLabels = {
  docTitle: 'Chat transcript',
  exportedOn: 'Exported on {date}',
  messageCount: '{count} messages',
  dateRange: 'Date range: {range}',
  generatedBy: 'Generated by WA Archiver',
  page: 'Page',
  groupChat: 'Group chat',
  starred: 'Starred',
  edited: 'edited',
  deleted: 'This message was deleted',
  repliedTo: 'Replied to {sender}',
  scheduled: 'Scheduled for {date}',
  poll: 'Poll',
  mediaPhoto: 'photo',
  mediaVideo: 'video',
  mediaAudio: 'voice note',
  mediaDocument: 'document',
  mediaSticker: 'sticker',
  mediaGif: 'GIF',
  mediaLocation: 'location',
  mediaContact: 'contact',
}

/**
 * i18n bridge: translate `key` with the app's t() while the pdf.* keys are
 * pending their locale-file merge; falls back to the English label (with
 * {param} interpolation) when the key isn't in the strings tables yet.
 * The `as unknown` cast is contained here so callers can pass a plain key.
 */
export function pdfT(
  tfn: (key: never, params?: TParams) => string,
  key: PdfKey,
  fallback: string,
  params?: TParams
): string {
  let out: string
  try {
    out = tfn(key as never, params)
  } catch {
    out = ''
  }
  // t() falls back to the raw key when a translation is missing.
  if (!out || out === key) return interpolate(fallback, params)
  return out
}

function interpolate(template: string, params?: TParams): string {
  if (!params) return template
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(params, name)
      ? String(params[name])
      : match
  )
}


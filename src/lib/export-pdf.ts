/**
 * PDF transcript export — zero-dependency, print-pipeline based.
 *
 * Builds a clean, professional, print-ready transcript document (A4 pages,
 * date separators, sender + time per message, media placeholders like
 * [photo: name], italic system lines, starred markers, reaction counts,
 * reply-quote indents) and prints it through a hidden iframe:
 *   • Capacitor/Android WebView → the Android print framework ("Save as PDF")
 *   • Desktop browsers → the native print dialog (destination: Save as PDF)
 *
 * This avoids bundling any PDF library (jsPDF etc.), keeps the APK small and
 * produces selectable text with proper page breaks — the browser/OS engine
 * handles pagination.
 *
 * ALL user content (sender names, bodies, media names, reaction emojis) is
 * HTML-escaped before being embedded; URLs are linkified only after
 * escaping. The document is rendered inside a sandboxed iframe via srcdoc,
 * so no script ever runs.
 */

import type { TParams } from '@/lib/i18n'


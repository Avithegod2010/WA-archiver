/** One transcript row — mirrors data/types.ts TranscriptMessage (no import
 *  to keep this module standalone for any caller shape). */
export interface PdfTranscriptMessage {
  ts: string | Date
  sender: string | null
  body: string
  type: string
  mediaName: string | null
  edited?: boolean
  /** deliverAt ISO for a pending scheduled send, else null. */
  scheduledFor?: string | Date | null
  pinned?: boolean | null
  starred?: boolean | null
  /** Emoji → reactor names map. */
  reactions?: Record<string, string[]> | null
  /** Quoted message this one replies to, when resolvable. */
  replyTo?: { sender: string; body: string } | null
}

/** Every visible document string, overridable for i18n (see pdfT). */
export interface PdfLabels {
  docTitle: string
  exportedOn: string
  messageCount: string
  dateRange: string
  generatedBy: string
  page: string
  groupChat: string
  starred: string
  edited: string
  deleted: string
  repliedTo: string
  scheduled: string
  poll: string
  mediaPhoto: string
  mediaVideo: string
  mediaAudio: string
  mediaDocument: string
  mediaSticker: string
  mediaGif: string
  mediaLocation: string
  mediaContact: string
}

export interface ExportChatInput {
  title: string
  isGroup?: boolean
  messages: PdfTranscriptMessage[]
  /** Translated labels; omitted keys fall back to English. */
  labels?: Partial<PdfLabels>
}

/** Keys this feature reads via t('pdf.*') — written to agent-ctx/keys-2b.json. */

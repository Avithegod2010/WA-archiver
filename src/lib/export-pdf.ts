function esc(s: string): string {
  return String(s)
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&#39;')
}

/** Linkify http(s) URLs — input must already be HTML-escaped. */
function linkify(safe: string): string {
  return safe.replace(/https?:\/\/[^\s<]+/g, (url) => `<u>${url}</u>`)
}

function pad2(n: number): string {
  return String(n).padStart(2, '0')
}

function asDate(v: string | Date): Date {
  return v instanceof Date ? v : new Date(v)
}

function fmtTime(d: Date): string {
  return `${pad2(d.getHours())}:${pad2(d.getMinutes())}`
}

function fmtDate(d: Date): string {
  return `${pad2(d.getDate())}/${pad2(d.getMonth() + 1)}/${d.getFullYear()}`
}

function fmtDateTime(d: Date): string {
  return `${fmtDate(d)} ${fmtTime(d)}`
}

function sameDay(a: Date, b: Date): boolean {
  return (
    a.getFullYear() === b.getFullYear() &&
    a.getMonth() === b.getMonth() &&
    a.getDate() === b.getDate()
  )
}

function dayLabel(d: Date): string {
  return d.toLocaleDateString(undefined, {
    weekday: 'long',
    day: 'numeric',
    month: 'long',
    year: 'numeric',
  })
}

const SENDER_COLORS = [
  '#b03a7a',
  '#027a7a',
  '#8a6d00',
  '#6a4fbf',
  '#c2542e',
  '#20706c',
  '#a44a72',
  '#5b7a1f',
]

/** Deterministic muted-per-print color per sender name. */
function colorFor(name: string): string {
  let h = 0
  for (let i = 0; i < name.length; i++) h = (h * 31 + name.charCodeAt(i)) >>> 0
  return SENDER_COLORS[h % SENDER_COLORS.length]
}

/** Media placeholder text, e.g. "[photo: IMG-20240101.jpg]". */
function mediaPlaceholder(msg: PdfTranscriptMessage, l: PdfLabels): string {
  const name = msg.mediaName || msg.body.trim() || 'media'
  let kind: string
  switch (msg.type) {
    case 'image': kind = l.mediaPhoto; break
    case 'sticker': kind = l.mediaSticker; break
    case 'gif': kind = l.mediaGif; break
    case 'video': kind = l.mediaVideo; break
    case 'audio': kind = l.mediaAudio; break
    case 'document': kind = l.mediaDocument; break
    case 'location': kind = l.mediaLocation; break
    case 'contact': kind = l.mediaContact; break
    default: kind = l.mediaPhoto
  }
  return `[${kind}: ${name}]`
}

/** Round-trip fallback bodies for special types (mirrors export-text.ts). */
function displayBody(msg: PdfTranscriptMessage, l: PdfLabels): string {
  let body = msg.body ?? ''
  switch (msg.type) {
    case 'deleted':
      return l.deleted
    case 'location':
      if (!body) body = `${l.mediaLocation}: ${msg.mediaName || ''}`.trim()
      return body
    case 'contact':
      if (!body) body = `${l.mediaContact}: ${msg.mediaName || ''}`.trim()
      return body
    case 'poll':
      if (!body) body = l.poll
      return body
    case 'call':
      return body || '📞'
    default:
      if (!body && msg.mediaName) return mediaPlaceholder(msg, l)
      if (!body) return mediaPlaceholder(msg, l)
      return body
  }
}

function parseReactions(
  raw: Record<string, string[]> | null | undefined
): Array<[string, number]> {
  if (!raw) return []
  return Object.entries(raw)
    .filter(
      (entry): entry is [string, string[]] =>
        Array.isArray(entry[1]) && entry[1].length > 0
    )
    .map(([emoji, senders]) => [emoji, senders.length] as [string, number])
}

function snippet(s: string, max: number): string {
  const clean = s.replace(/\s+/g, ' ').trim()
  return clean.length > max ? `${clean.slice(0, max - 1)}…` : clean
}

/* ------------------------------------------------------------------ */
/* Document builder                                                    */
/* ------------------------------------------------------------------ */

export function buildChatPdfHtml(chat: ExportChatInput): string {
  const l: PdfLabels = { ...EN_LABELS, ...(chat.labels ?? {}) }
  const messages = chat.messages
  const rows: string[] = []
  let prev: Date | null = null

  for (const msg of messages) {
    const ts = asDate(msg.ts)
    if (isNaN(ts.getTime())) continue
    if (!prev || !sameDay(prev, ts)) {
      rows.push(`<div class="day"><span>${esc(dayLabel(ts))}</span></div>`)
    }
    prev = ts

    // System / call events — centered italic lines.
    if (msg.type === 'system' || msg.type === 'call') {
      rows.push(
        `<div class="sys">${esc(displayBody(msg, l))}</div>`
      )
      continue
    }

    const sender = msg.sender || ''
    const time = fmtTime(ts)
    const headSender = sender
      ? `<span class="sender" style="color:${colorFor(sender)}">${esc(sender)}</span>`
      : ''
    const headTime = `<span class="time">${esc(time)}</span>`

    // Reply quote — indented block above the body.
    const quote = msg.replyTo?.sender
      ? `<div class="quote"><span class="qwho">${esc(
          interpolate(l.repliedTo, { sender: msg.replyTo.sender })
        )}:</span> ${esc(snippet(msg.replyTo.body || '', 140))}</div>`
      : ''

    // Scheduled prefix.
    const schedDate = msg.scheduledFor ? asDate(msg.scheduledFor) : null
    const sched =
      schedDate && !isNaN(schedDate.getTime())
        ? `<div class="sched">${esc(
            interpolate(l.scheduled, { date: fmtDateTime(schedDate) })
          )}</div>`
        : ''

    // Body (or media placeholder / tombstone).
    const bodyText = displayBody(msg, l)
    const isMediaOnly =
      !msg.body?.trim() &&
      !['deleted', 'system', 'call'].includes(msg.type)
    const bodyHtml = isMediaOnly
      ? `<div class="media">${esc(bodyText)}</div>`
      : `<div class="body">${linkify(esc(bodyText)).replaceAll('\n', '<br>')}</div>`

    // Flags: starred / edited / pinned.
    const flags = [
      msg.starred ? `<span class="star" title="${esc(l.starred)}">★</span>` : '',
      msg.edited ? `<span class="edited">${esc(l.edited)}</span>` : '',
      msg.pinned ? '<span class="pin">📌</span>' : '',
    ]
      .filter(Boolean)
      .join(' ')

    // Reaction counts: 👍 ×3.
    const reacts = parseReactions(msg.reactions)
    const reactsHtml = reacts.length
      ? `<div class="reacts">${reacts
          .map(
            ([emoji, n]) =>
              `<span class="react">${esc(emoji)} <i>×${n}</i></span>`
          )
          .join('')}</div>`
      : ''

    rows.push(
      `<div class="msg"><div class="head">${headSender}${headTime}</div>${sched}${quote}${bodyHtml}${
        flags || reactsHtml
          ? `<div class="meta">${flags}${reactsHtml}</div>`
          : ''
      }</div>`
    )
  }

  const first = messages.length ? asDate(messages[0].ts) : null
  const last = messages.length ? asDate(messages[messages.length - 1].ts) : null
  let range = ''
  if (first && !isNaN(first.getTime()) && last && !isNaN(last.getTime())) {
    range = sameDay(first, last) ? fmtDate(first) : `${fmtDate(first)} – ${fmtDate(last)}`
  }

  const metaLines = [
    interpolate(l.exportedOn, { date: fmtDateTime(new Date()) }),
    range ? interpolate(l.dateRange, { range }) : '',
    interpolate(l.messageCount, { count: messages.length }),
    chat.isGroup ? l.groupChat : '',
  ].filter(Boolean)

  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>${esc(chat.title)} — ${esc(l.docTitle)}</title>
<style>
  @page { size: A4; margin: 18mm 15mm 20mm; }
  * { box-sizing: border-box; }
  html, body { margin: 0; padding: 0; }
  body { font: 11.5pt/1.5 Georgia, 'Times New Roman', serif; color: #1a1a1a; }
  header.doc { border-bottom: 2px solid #1a1a1a; padding-bottom: 10px; margin-bottom: 16px; }
  header.doc h1 { margin: 0 0 4px; font-size: 17pt; line-height: 1.3; }
  header.doc .meta { font-size: 9.5pt; color: #444; line-height: 1.6; }
  header.doc .brand { margin-top: 6px; font-size: 9pt; color: #666; font-style: italic; }
  .day { text-align: center; margin: 18px 0 10px; }
  .day span { display: inline-block; font-size: 9.5pt; font-weight: bold;
    letter-spacing: .04em; text-transform: uppercase; color: #333;
    border: 1px solid #999; border-radius: 3px; padding: 2px 10px; }
  .sys { text-align: center; font-style: italic; color: #555;
    font-size: 10pt; margin: 6px 24px; }
  .msg { margin: 7px 0; padding-left: 10px; border-left: 2px solid #ddd;
    page-break-inside: avoid; break-inside: avoid; }
  .msg .head { font-size: 9.5pt; margin-bottom: 1px; }
  .msg .sender { font-weight: bold; }
  .msg .time { color: #666; margin-left: 6px; font-size: 8.5pt; }
  .msg .body { word-wrap: break-word; overflow-wrap: break-word; }
  .msg .body u { text-decoration: underline; }
  .msg .media { font-style: italic; color: #333; }
  .msg .quote { border-left: 3px solid #bbb; background: #f4f4f4;
    padding: 3px 8px; margin: 2px 0 4px; font-size: 9.5pt; color: #444; }
  .msg .quote .qwho { font-weight: bold; }
  .msg .sched { font-size: 9pt; color: #7a5b00; font-style: italic; margin: 1px 0; }
  .msg .meta { margin-top: 2px; font-size: 9pt; color: #555; }
  .msg .star { color: #b8860b; font-weight: bold; }
  .msg .edited { font-style: italic; font-size: 8.5pt; }
  .msg .react { display: inline-block; border: 1px solid #ccc; border-radius: 8px;
    padding: 0 5px; margin-right: 4px; }
  .msg .react i { font-style: normal; font-size: 8.5pt; }
  footer.brand { position: fixed; bottom: 0; left: 0; right: 0;
    text-align: center; font-size: 8.5pt; color: #777; }
  @media print { footer.brand { position: fixed; } }
</style>
</head>
<body>
<header class="doc">
  <h1>${esc(chat.title)}</h1>
  <div class="meta">${metaLines.map(esc).join(' · ')}</div>
  <div class="brand">${esc(l.generatedBy)}</div>
</header>
${rows.join('\n')}
<footer class="brand">${esc(l.generatedBy)} — ${esc(chat.title)}</footer>
</body>
</html>
`
}


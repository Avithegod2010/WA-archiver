/**
 * Build the transcript document and open the platform print dialog on it
 * (Android print framework → "Save as PDF" in the Capacitor WebView; the
 * native print dialog on desktop). Never throws into the caller's UI.
 */
export function exportChatPdf(chat: ExportChatInput): void {
  if (typeof document === 'undefined') return
  const html = buildChatPdfHtml(chat)

  const iframe = document.createElement('iframe')
  iframe.setAttribute('aria-hidden', 'true')
  iframe.style.position = 'fixed'
  iframe.style.right = '0'
  iframe.style.bottom = '0'
  iframe.style.width = '1px'
  iframe.style.height = '1px'
  iframe.style.opacity = '0'
  iframe.style.border = '0'

  let done = false
  const cleanup = () => {
    if (done) return
    done = true
    try {
      iframe.remove()
    } catch {
      /* already gone */
    }
  }

  iframe.onload = () => {
    try {
      const win = iframe.contentWindow
      if (!win) throw new Error('no content window')
      win.onafterprint = cleanup
      win.focus()
      win.print()
      // Safety net: remove the frame even if afterprint never fires.
      window.setTimeout(cleanup, 60_000)
    } catch {
      // Fallback: open the document in a temporary window and print there.
      cleanup()
      try {
        const win = window.open('', '_blank')
        if (!win) return
        win.document.write(html)
        win.document.close()
        win.focus()
        win.print()
      } catch {
        /* printing unavailable on this device */
      }
    }
  }

  document.body.appendChild(iframe)
  // srcdoc keeps the transcript fully self-contained (no network fetches).
  iframe.setAttribute('srcdoc', html)
}
